const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

/**
 * Trust certificate authorities the user installed on the phone, besides the system ones, so a
 * self-hosted server with its own certificate works over HTTPS (help screen: `/login/https-help`).
 * Android ignores user certificates for apps targeting API 24+ unless the app opts in.
 *
 * A network security config replaces `usesCleartextTraffic`, so debug builds get their own copy
 * that still allows cleartext for Metro. Release builds allow HTTPS only.
 */
const config = (cleartext) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-user-certificates.js -->
<network-security-config>
    <base-config cleartextTrafficPermitted="${cleartext}">
        <trust-anchors>
            <certificates src="system" />
            <certificates src="user" />
        </trust-anchors>
    </base-config>
</network-security-config>
`;

module.exports = function withUserCertificates(expoConfig) {
  expoConfig = withAndroidManifest(expoConfig, (mod) => {
    const application = mod.modResults.manifest.application?.[0];
    if (!application) throw new Error('with-user-certificates: <application> not found');
    application.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    return mod;
  });
  return withDangerousMod(expoConfig, [
    'android',
    (mod) => {
      const src = path.join(mod.modRequest.platformProjectRoot, 'app', 'src');
      for (const [variant, cleartext] of [
        ['main', false],
        ['debug', true],
        ['debugOptimized', true],
      ]) {
        const dir = path.join(src, variant, 'res', 'xml');
        fs.mkdirSync(dir, { recursive: true });
        fs.writeFileSync(path.join(dir, 'network_security_config.xml'), config(cleartext));
      }
      return mod;
    },
  ]);
};
