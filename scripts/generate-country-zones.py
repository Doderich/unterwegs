#!/usr/bin/env python3
"""Writes src/time/countryZones.ts from the IANA zone.tab (country code, reference coordinates, zone).

Usage: python3 scripts/generate-country-zones.py [/usr/share/zoneinfo/zone.tab]
Only zones the server accepts (src/time/zones.ts) are kept, so a suggested zone can always be saved.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
tab = Path(sys.argv[1] if len(sys.argv) > 1 else '/usr/share/zoneinfo/zone.tab')
server = set(re.findall(r"'([^']+)'", (ROOT / 'src/time/zones.ts').read_text()))


def coord(text: str, degree_digits: int) -> float:
    sign = -1 if text[0] == '-' else 1
    digits = text[1:]
    deg = int(digits[:degree_digits])
    minutes = int(digits[degree_digits:degree_digits + 2])
    seconds = int(digits[degree_digits + 2:] or 0)
    return round(sign * (deg + minutes / 60 + seconds / 3600), 2)


zones: dict[str, list[tuple[str, float, float]]] = {}
for line in tab.read_text().splitlines():
    if not line or line.startswith('#'):
        continue
    code, coords, zone = line.split('\t')[:3]
    if zone not in server:
        continue
    m = re.match(r'^([+-]\d+)([+-]\d+)$', coords)
    lat_text, lon_text = m.group(1), m.group(2)
    lat = coord(lat_text, 2)
    lon = coord(lon_text, 3)
    zones.setdefault(code, []).append((zone, lat, lon))

lines = [
    '/**',
    ' * Time zones per country with a reference point each (IANA zone.tab), for a zone from a place.',
    ' * Generated by scripts/generate-country-zones.py; only zones the server accepts.',
    ' */',
    'export const COUNTRY_ZONES: Record<string, readonly (readonly [zone: string, lat: number, lon: number])[]> = {',
]
for code in sorted(zones):
    entries = ', '.join(f"['{z}', {lat}, {lon}]" for z, lat, lon in zones[code])
    lines.append(f'  {code}: [{entries}],')
lines.append('};')
(ROOT / 'src/time/countryZones.ts').write_text('\n'.join(lines) + '\n')
print(f'{len(zones)} countries, {sum(len(v) for v in zones.values())} zones')
